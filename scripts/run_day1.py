"""Reproduce all Day 1 results with one command:

    python -m scripts.run_day1      (or: make day1)

Steps: generate synthetic data -> export JSON Schemas -> validate test set -> run baselines -> score -> comparison table.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timezone

from baselines import keyword_baseline, naive_llm_baseline
from eval.metrics import evaluate, to_markdown
from scripts import generate_synthetic, pain_model
from src.schemas import export_json_schemas, load_test_cases
from src.taxonomy import ROOT, load_settings

COMPARE_KEYS = ["case_pass_rate", "schema_validity_rate", "intent_accuracy", "priority_exact_accuracy",
                "under_prioritization_count", "routing_accuracy", "escalation_recall", "escalation_precision",
                "escalation_reason_recall", "missing_info_recall", "critical_failure_cases", "injection_pass",
                "human_touch_rate", "latency_ms_median", "cost_usd_per_ticket_mean"]


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # Windows consoles default to cp1252
    s = load_settings()
    results_dir = ROOT / s["paths"]["results_dir"]
    print("== 1/5 generate synthetic data"); generate_synthetic.main()
    print("== 2/5 export JSON schemas"); [print("wrote", p) for p in export_json_schemas(ROOT / "schemas")]
    print("== 3/5 validate test set"); cases = load_test_cases(ROOT / s["paths"]["test_cases"]); print(f"{len(cases)} test cases valid")

    print("== 3b compute pain model (estimate)"); pain_model.main()
    print("== 4/5 run baselines")
    keyword_baseline.run(); print("keyword_baseline: done")
    naive_status = naive_llm_baseline.run()

    print("== 5/5 score")
    summaries: dict[str, dict | None] = {}
    md_parts = []
    for name in ["keyword_baseline", "naive_llm_baseline"]:
        pred = results_dir / f"{name}_predictions.jsonl"
        if name == "naive_llm_baseline" and naive_status == "not_run":
            summaries[name] = None
            md_parts.append(f"### {name}\n\n**NOT RUN** — no ANTHROPIC_API_KEY in `.env`. No numbers recorded.\n")
            continue
        res = evaluate(pred)
        (results_dir / f"{name}_results.json").write_text(json.dumps(res, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        md = to_markdown(name, res)
        (results_dir / f"{name}_results.md").write_text(md, encoding="utf-8")
        summaries[name] = res["summary"]
        md_parts.append(md)

    header = ["| Metric | " + " | ".join(summaries) + " |", "|---|" + "---|" * len(summaries)]
    rows = []
    for k in COMPARE_KEYS:
        cells = []
        for v in summaries.values():
            if v is None:
                cells.append("not run")
            else:
                x = v[k]
                if x is None: cells.append("n/a")
                elif isinstance(x, bool): cells.append("PASS" if x else "FAIL")
                elif k.endswith(("_rate", "_accuracy", "_recall", "_precision")): cells.append(f"{x:.0%}")
                elif k.startswith("cost"): cells.append(f"${x:.6f}")
                else: cells.append(str(x))
        rows.append(f"| {k} | " + " | ".join(cells) + " |")
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = ("# Day 1 baseline comparison\n\n"
           f"_Measured on the 12-case SYNTHETIC test set. Generated by `python -m scripts.run_day1` at {stamp}._\n\n"
           + "\n".join(header + rows) + "\n\n## Per-case detail\n\n" + "\n".join(md_parts))
    (results_dir / "baseline_comparison.md").write_text(out, encoding="utf-8")
    (results_dir / "baseline_summary.json").write_text(json.dumps(summaries, indent=2) + "\n", encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
