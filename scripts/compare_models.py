"""Compare every archived LLM run and pick the best-suited model with a rule fixed IN ADVANCE.

    python -m scripts.compare_models            # writes eval/results/model_comparison.md
    python -m scripts.compare_models --apply    # also sets config/settings.yaml llm.model to the winner
    python -m scripts.compare_models --rescore  # re-parse + re-score all archived runs with current code first

Each run lives in eval/results/archive/<model>/ (written automatically by scripts.run_day1).

Selection rule (written before the qwen3.8-27b run was seen; ADR-016). Lexicographic, best first:
  1. fewest critical-failure cases                 (safety)
  2. highest escalation recall                     (safety)
  3. fewest under-prioritised P1/P2                (safety)
  4. injection case passed                         (safety)
  5. highest case pass rate                        (quality)
  6. highest priority exact accuracy               (quality)
  7. lowest human-touch rate                       (operating cost)
  8. lowest median latency                         (operating cost)
Price per token is not used yet because no prices are confirmed.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from src.taxonomy import ROOT

ARCHIVE = ROOT / "eval" / "results" / "archive"
OUT = ROOT / "eval" / "results" / "model_comparison.md"


def load_runs() -> dict[str, dict]:
    runs = {}
    for d in sorted(p for p in ARCHIVE.iterdir() if p.is_dir()):
        f = d / "naive_llm_baseline_results.json"
        if f.exists():
            runs[d.name] = json.loads(f.read_text(encoding="utf-8"))["summary"]
    return runs


def sort_key(s: dict) -> tuple:
    return (s["critical_failure_cases"], -(s["escalation_recall"] or 0), s["under_prioritization_count"],
            0 if s["injection_pass"] else 1, -(s["case_pass_rate"] or 0), -(s["priority_exact_accuracy"] or 0),
            s["human_touch_rate"] or 1, s["latency_ms_median"] or float("inf"))


ROWS = [
    ("Case pass rate", "case_pass_rate", "pct"), ("Critical-failure cases", "critical_failure_cases", "int"),
    ("Escalation recall (safety)", "escalation_recall", "pct"), ("Escalation precision", "escalation_precision", "pct"),
    ("Under-prioritised P1/P2", "under_prioritization_count", "int"), ("Injection case (TC10)", "injection_pass", "bool"),
    ("Intent accuracy", "intent_accuracy", "pct"), ("Priority exact accuracy", "priority_exact_accuracy", "pct"),
    ("Routing accuracy", "routing_accuracy", "pct"), ("Escalation-reason recall", "escalation_reason_recall", "pct"),
    ("Missing-info recall", "missing_info_recall", "pct"), ("Human-touch rate", "human_touch_rate", "pct"),
    ("Median latency", "latency_ms_median", "sec"), ("Tokens per ticket (in / out)", "tokens_per_ticket_mean", "tok"),
    ("Cost per ticket", "cost_usd_per_ticket_mean", "usd"),
]


def fmt(v, kind: str) -> str:
    if v is None:
        return "TBC" if kind == "usd" else "n/a"
    return {"pct": lambda: f"{v:.0%}", "int": lambda: str(v), "bool": lambda: "PASS" if v else "FAIL",
            "sec": lambda: f"{v / 1000:.1f} s", "tok": lambda: f"{v['input']:.0f} / {v['output']:.0f}",
            "usd": lambda: f"${v:.6f}"}[kind]()


def build() -> tuple[str, str]:
    runs = load_runs()
    if not runs:
        raise SystemExit("no archived runs in eval/results/archive/")
    ranked = sorted(runs, key=lambda m: sort_key(runs[m]))
    winner = ranked[0]
    kw_path = ROOT / "eval" / "results" / "keyword_baseline_results.json"
    kw = json.loads(kw_path.read_text(encoding="utf-8"))["summary"] if kw_path.exists() else None
    cols = (["Keyword rules"] if kw else []) + [f"`{m}`" + (" **(selected)**" if m == winner else "") for m in ranked]
    lines = ["# Model comparison: naive LLM baseline (one free-text prompt)", "",
             "_Same 12 SYNTHETIC cases, prompt, parser and scorer. One run per model, so outputs are not deterministic "
             "and one case = 8.3 points. Generated by `python -m scripts.compare_models`._", "",
             "| Metric | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for label, key, kind in ROWS:
        cells = ([fmt(kw[key], kind)] if kw else []) + [fmt(runs[m][key], kind) for m in ranked]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines += ["", "## Selection", "",
              "Rule fixed before the last run (ADR-016), applied in order: fewest critical failures, then escalation "
              "recall, then under-prioritisation, then injection, then case pass rate, then priority accuracy, then "
              "human-touch rate, then latency. Price is not used until per-token prices are confirmed.", "",
              "Ranking: " + " > ".join(f"`{m}`" for m in ranked), "",
              f"**Selected: `{winner}`.** With n = 12 and one run each, gaps of one case are within noise."]
    return "\n".join(lines) + "\n", winner


def apply_winner(model: str) -> None:
    p = ROOT / "config" / "settings.yaml"
    s = p.read_text(encoding="utf-8")
    s2 = re.sub(r"(?m)^  model: .*$", f"  model: {model}   # selected by scripts.compare_models (ADR-016)", s, count=1)
    p.write_text(s2, encoding="utf-8")


def rescore_all() -> None:
    """Re-parse and re-score every archived run with the CURRENT parser and scorer (no API calls),
    so all models are judged by identical code."""
    from baselines.naive_llm_baseline import reparse
    from eval.metrics import evaluate, to_markdown

    for d in sorted(p for p in ARCHIVE.iterdir() if p.is_dir()):
        pred = d / "naive_llm_baseline_predictions.jsonl"
        if not pred.exists():
            continue
        reparse(pred)
        res = evaluate(pred)
        (d / "naive_llm_baseline_results.json").write_text(json.dumps(res, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        (d / "naive_llm_baseline_results.md").write_text(to_markdown(f"naive_llm_baseline ({d.name})", res), encoding="utf-8")
        print(f"re-scored {d.name}: pass rate {res['summary']['case_pass_rate']:.0%}")


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if "--rescore" in sys.argv:
        rescore_all()
    md, winner = build()
    OUT.write_text(md, encoding="utf-8")
    print(md)
    if "--apply" in sys.argv:
        apply_winner(winner)
        print(f"config/settings.yaml llm.model -> {winner}")


if __name__ == "__main__":
    main()
