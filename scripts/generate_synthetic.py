def generate_customers(seed: int, ref: date) -> list[dict]:
    rng = random.Random(seed)
    names = rng.sample(_PREFIX, k=len(_PREFIX))
    customers = []
    for i in range(25):
        cid = f"CUST-{1001 + i}"
        trade = rng.choice(_TRADE)
        # Draw random attributes for every account (keeps the RNG stream stable), then apply anchor overrides.
        attrs = {
            "plan_tier": rng.choices(["starter", "professional", "enterprise"], weights=[4, 5, 2])[0],
            "seat_count": rng.randint(3, 120),
            "open_incidents": rng.choices([0, 1, 2], weights=[7, 2, 1])[0],
            "account_health": rng.choices(["green", "amber", "red"], weights=[6, 3, 1])[0],
            "renewal_offset_days": rng.randint(10, 365),
            "onboarding": False,
        }
        attrs.update(ANCHORS.get(cid, {}))
        customers.append({
            "customer_id": cid,
            "company_name": f"{names[i]} {trade} (Synthetic)",
            "trade": trade,
            "plan_tier": attrs["plan_tier"],
            "seat_count": attrs["seat_count"],
            "contract_renewal_date": (ref + timedelta(days=attrs["renewal_offset_days"])).isoformat(),
            "open_incidents": attrs["open_incidents"],
            "account_health": attrs["account_health"],
            "onboarding_in_progress": attrs["onboarding"],
            "primary_contact_domain": f"{names[i].lower()}.example",
        })
    return customers


def generate_kb() -> list[dict]:
    return [{"article_id": a, "title": t, "intent": i, "body": b} for a, t, i, b in KB_ARTICLES]


def main() -> None:
    s = load_settings()
    ref = date.fromisoformat(s["reference_date"])
    out = ROOT / "data" / "synthetic"
    out.mkdir(parents=True, exist_ok=True)
    for fname, records in {"customers.json": generate_customers(s["seed"], ref), "kb_articles.json": generate_kb()}.items():
        payload = {"_notice": BANNER, "reference_date": s["reference_date"], "records": records}
        (out / fname).write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {out / fname} ({len(records)} records)")


if __name__ == "__main__":
    main()
